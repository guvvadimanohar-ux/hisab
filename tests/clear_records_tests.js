const assert = require('node:assert/strict');
const { initializeDatabase } = require('../backend/services/database');
const auth = require('../backend/services/authService');
const { handleClearRecordsRoutes } = require('../backend/api/clearRecords');
const db = initializeDatabase(':memory:');
const first = auth.createUserWithSession(db, { shopName: 'A', fullName: 'A', phone: '9000000001', password: 'test123' }).userId;
const second = auth.createUserWithSession(db, { shopName: 'B', fullName: 'B', phone: '9000000002', password: 'test123' }).userId;
let user = { id: first }, result;
const context = { db, helpers: { requireAuth: (_req, res) => { if (!user) result = { status: 401 }; return user; }, guardMutation: () => true, sendJson: (_res, status, body) => result = { status, ...body }, sendError: (_res, status, code) => result = { status, code } } };
const call = async (resource, action) => { await handleClearRecordsRoutes({ method: action === 'backup' ? 'GET' : 'POST' }, {}, `/api/records/${resource}/${action}`, null, context); return result; };
for (const [id, owner] of [['ca', first], ['cb', second]]) db.prepare('INSERT INTO customers (id,shop_id,user_id,name,created_at,updated_at) VALUES (?, ?, ?, ?, ?, ?)').run(id, 'shop', owner, id, 'now', 'now');
db.prepare('INSERT INTO credits (id,shop_id,user_id,customer_id,amount,outstanding_amount,issued_at,created_at,updated_at) VALUES (?,?,?,?,?,?,?,?,?)').run('credit', 'shop', first, 'ca', 100, 100, 'now', 'now', 'now');
db.prepare('INSERT INTO datasets (id,name,uploaded_at) VALUES (?,?,?)').run('ds','Test','now');
for (const [id,owner] of [['ta', first], ['tb', second]]) db.prepare('INSERT INTO transactions (id,dataset_id,date,customer_name,amount,transaction_type,cash_flow_type,created_at,user_id) VALUES (?,?,?,?,?,?,?,?,?)').run(id,'ds','2026-10-05','Test',100,'SALE','INFLOW','now',owner);
(async () => {
  assert.equal((await call('transactions','clear')).data.count, 1);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM transactions WHERE user_id=?').get(second).n, 1);
  assert.equal((await call('transactions','backup')).data.canUndo,true);
  assert.equal((await call('transactions','clear')).status,409);
  assert.equal((await call('transactions','restore')).status,200);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM transactions').get().n,2);
  assert.equal((await call('customers','clear')).data.count,1);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM credits').get().n,0);
  user = { id: second }; assert.equal((await call('customers','restore')).status,404);
  user = { id: first }; assert.equal((await call('customers','restore')).status,200);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM credits').get().n,1);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM customers').get().n,2);
  user = null; assert.equal((await call('transactions','clear')).status,401);
  console.log('PASS: clear/restore, persistent backups, repeat-clear protection, linked credits, merchant isolation and authentication.');
  db.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
